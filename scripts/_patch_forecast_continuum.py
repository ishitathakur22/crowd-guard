    "            1 for h in hazards\n"
    "            if h.severity in (AlertSeverity.CRITICAL, AlertSeverity.EMERGENCY)\n"
    "        )\n"
    "        return PredictionSnapshot(\n"
    "            timestamp_offset_sec=round(time_offset, 1),\n"
